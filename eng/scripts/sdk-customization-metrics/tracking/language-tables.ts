// Renders tracking/languages/<language>.md: one language's column of tracking/features.json as a
// table its emitter owners can review (`cli.ts language-tables`). The JSON stays the source;
// a test fails when the rendered files are out of date.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { LANGUAGES } from "../web/languages.ts";
import { patternLabel } from "../web/data.ts";
import { COVERAGE_LABELS, SUPPORT_LABELS } from "../web/tracking.ts";
import type { FeatureMap, LanguageCapability, LanguageId, PatternCatalog } from "../web/types.ts";

const HERE = fileURLToPath(new URL("./", import.meta.url));

const cell = (text: string | undefined) =>
  (text ?? "").replaceAll("|", "\\|").replaceAll("\n", " ").trim();

const needsAttention = (capability: LanguageCapability) =>
  capability.support === "language-limitation" ||
  capability.support === "not-applicable" ||
  capability.confidence === "low" ||
  /sign-off/i.test(capability.note ?? "");

export function renderLanguageTable(
  map: FeatureMap,
  names: Map<string, string>,
  language: LanguageId,
): string {
  const label = LANGUAGES.find((item) => item.id === language)?.label ?? language;
  const name = (id: string) => names.get(id) ?? patternLabel(id);
  const patternsByFeature = new Map<string, string[]>();
  for (const [id, entry] of Object.entries(map.patterns)) {
    if (!patternsByFeature.has(entry.feature)) patternsByFeature.set(entry.feature, []);
    patternsByFeature.get(entry.feature)!.push(id);
  }
  const features = Object.entries(map.features)
    .filter(([, feature]) => feature.languages?.[language])
    .sort(
      ([a], [b]) =>
        (patternsByFeature.get(b)?.length ?? 0) - (patternsByFeature.get(a)?.length ?? 0) ||
        a.localeCompare(b),
    );
  const counts = new Map<string, number>();
  for (const [, feature] of features) {
    const support = feature.languages![language]!.support;
    counts.set(support, (counts.get(support) ?? 0) + 1);
  }
  const row = (key: string, feature: (typeof features)[number][1]) => {
    const capability = feature.languages![language]!;
    const patterns = patternsByFeature.get(key) ?? [];
    const sample = patterns.slice(0, 3).map(name).join("; ");
    return `| ${cell(feature.name)} | ${COVERAGE_LABELS[feature.coverage]} | **${SUPPORT_LABELS[capability.support]}** | ${capability.confidence} | ${cell(capability.note)} | ${patterns.length}${sample ? ` (${cell(sample)}${patterns.length > 3 ? "; …" : ""})` : ""} |`;
  };
  const header = [
    `| Feature | Overall coverage | ${label} support | Confidence | Note | Patterns it covers |`,
    "| --- | --- | --- | --- | --- | --- |",
  ];
  const attention = features.filter(([, feature]) => needsAttention(feature.languages![language]!));
  const overrides = Object.entries(map.patterns)
    .filter(([, entry]) => entry.languages?.[language])
    .sort(([a], [b]) => a.localeCompare(b));
  const lines = [
    `# ${label}: can the generator produce it? (draft for review)`,
    "",
    `Generated from \`tracking/features.json\` by \`cli.ts language-tables\`; do not edit this file. To change a call, edit \`features.<feature>.languages.${language}\` (or \`patterns.<id>.languages.${language}\`) in \`tracking/features.json\`, or comment on the pull request. The criteria and the meaning of each value are in [\`guidelines/capabilities.md\`](../../guidelines/capabilities.md).`,
    "",
    `Each row is a TypeSpec, TCGC or emitter feature that would remove a group of handwritten customizations, with this language's support for it. "Overall coverage" is the feature across all languages. The calls were drafted by AI from the TCGC docs and emitter tests and need a ${label} owner's review.`,
    "",
    `**${features.length} features:** ${[...counts]
      .sort((a, b) => b[1] - a[1])
      .map(
        ([support, count]) =>
          `${count} ${SUPPORT_LABELS[support as LanguageCapability["support"]].toLowerCase()}`,
      )
      .join(", ")}.`,
    "",
    "## Confirm these first",
    "",
    attention.length
      ? "Low-confidence calls, calls that need a design decision, and anything marked not applicable or a language limitation."
      : "Nothing is low-confidence or marked not applicable for this language.",
    "",
    ...(attention.length
      ? [...header, ...attention.map(([key, feature]) => row(key, feature)), ""]
      : []),
    "## All features",
    "",
    ...header,
    ...features.map(([key, feature]) => row(key, feature)),
    "",
    "## Pattern-specific calls",
    "",
    overrides.length
      ? `Patterns whose ${label} support differs from their feature's row.`
      : `No pattern differs from its feature's row for ${label}.`,
    "",
    ...(overrides.length
      ? [
          `| Pattern | Feature | ${label} support | Confidence | Note |`,
          "| --- | --- | --- | --- | --- |",
          ...overrides.map(([id, entry]) => {
            const capability = entry.languages![language]!;
            return `| ${cell(name(id))} (\`${id}\`) | ${cell(map.features[entry.feature]?.name ?? entry.feature)} | **${SUPPORT_LABELS[capability.support]}** | ${capability.confidence} | ${cell(capability.note)} |`;
          }),
          "",
        ]
      : []),
  ];
  return `${lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}

// Pattern names from the catalog and the reclassification files (ids otherwise in words).
export async function patternNames(): Promise<Map<string, string>> {
  const catalog: PatternCatalog = JSON.parse(
    await readFile(new URL("../guidelines/patterns.json", import.meta.url), "utf8"),
  );
  const names = new Map(catalog.patterns.map((item) => [item.id, item.name ?? item.id]));
  const reclassify = new URL("../reclassify/typed-wrappers.json", import.meta.url);
  const extra = JSON.parse(await readFile(reclassify, "utf8")) as {
    patterns: { id: string; name: string }[];
  };
  for (const item of extra.patterns) if (!names.has(item.id)) names.set(item.id, item.name);
  return names;
}

export async function renderLanguageTables(): Promise<Map<string, string>> {
  const map: FeatureMap = JSON.parse(await readFile(join(HERE, "features.json"), "utf8"));
  const names = await patternNames();
  return new Map(
    LANGUAGES.map((language) => [
      join(HERE, "languages", `${language.id}.md`),
      renderLanguageTable(map, names, language.id),
    ]),
  );
}

export async function writeLanguageTables(): Promise<string[]> {
  await mkdir(join(HERE, "languages"), { recursive: true });
  const files = await renderLanguageTables();
  for (const [path, text] of files) await writeFile(path, text);
  return [...files.keys()];
}
