// Deterministic customization entry points: files (and, for Java, members) that the language
// guidelines (guidelines/<language>.md) say are handwritten. These are candidates for review,
// not classified findings. Keep this file in step with the guidelines.

import type { NavigationLink } from "./web/types.ts";

// Package-level facts some languages need (see navigationContext).
export interface NavigationContext {
  generatedFolders?: string[];
}
// A navigation link before the caller adds the content hash.
export type NavigationCandidate = Omit<NavigationLink, "contentHash">;

const EXCLUDED =
  /(?:^|\/)(?:tests?|testdata|samples?[^/]*|GeneratorStubs|Properties|examples?)(?:\/|$)/i;
const GENERATED_HEADER =
  /auto[- ]generated|automatically generated|code generated|DO NOT EDIT|<auto-generated/i;

// Python libraries that wrap a generated package keep it in a folder ending in "generated".
export function pythonGeneratedFolders(paths: string[]): string[] {
  const folders = new Set<string>();
  for (const path of paths) {
    const parts = path.split("/");
    for (let index = 0; index < parts.length - 1; index++)
      if (/generated$/i.test(parts[index])) folders.add(parts.slice(0, index + 1).join("/"));
  }
  return [...folders];
}

// Package-level facts some languages need (computed once from the package's file list).
export function navigationContext(language: string, paths: string[]): NavigationContext {
  return language === "python" ? { generatedFolders: pythonGeneratedFolders(paths) } : {};
}

export function entryPoint(
  language: string,
  path: string,
  context: NavigationContext = {},
): string {
  if (EXCLUDED.test(path)) return "";
  if (language === "python") {
    if (!path.endsWith(".py")) return "";
    const inGenerated = (context.generatedFolders ?? []).some((folder) =>
      path.startsWith(`${folder}/`),
    );
    if (/(?:^|\/)_patch\.py$/.test(path) && !inGenerated) return "Python patch";
    if (context.generatedFolders?.length && !inGenerated)
      return "Python code wrapping generated folder";
    return "";
  }
  if (language === "java") {
    if (!path.endsWith(".java")) return "";
    if (/\/customizations?\//.test(path)) return "Java customization script";
    if (/\/src\/main\/java\//.test(path) && !/\/(?:package-info|module-info)\.java$/.test(path))
      return "Java handwritten source";
    return "";
  }
  if (language === "dotnet") {
    if (/(?:^|\/)generated(?:\/|$)/i.test(path)) return "";
    if (/\/src\/.*\.cs$/.test(path) && !/GlobalSuppressions\.cs$/.test(path))
      return "C# handwritten source candidate";
    return "";
  }
  if (language === "javascript") {
    if (/(?:^|\/)generated(?:\/|$)/i.test(path)) return "";
    return /\/src\/.*\.[jt]s$/.test(path) ? "JavaScript source overlay candidate" : "";
  }
  if (language === "go") {
    // Any handwritten file counts, even inside internal/generated.
    if (!path.endsWith(".go") || /_test\.go$|(?:^|\/)zz_[^/]*\.go$/.test(path)) return "";
    return /(?:^|\/)custom[^/]*\.go$/.test(path) ? "Go custom source" : "Go handwritten source";
  }
  return "";
}

const lineCount = (text: string) => text.split("\n").length - (text.endsWith("\n") ? 1 : 0);

// Java members declared without @Generated in a file that uses @Generated.
export function javaHandwrittenMembers(text: string): { name: string; line: number }[] {
  const lines = text.split("\n");
  const members: { name: string; line: number }[] = [];
  const declaration =
    /^\s+(?:(?:public|protected|private|static|final|abstract|synchronized|native|default)\s+)+(?:<[^>]+>\s+)?(?:[\w.<>[\],?]+(?:\s*<[^;{]*>)?\s+)?(\w+)\s*\(/;
  for (const [index, line] of lines.entries()) {
    const match = declaration.exec(line);
    if (!match || /\b(?:return|new|else|throw)\b/.test(line.split("(")[0])) continue;
    // Walk back over annotations, Javadoc and blank lines to find @Generated.
    let generated = false;
    for (let back = index - 1; back >= 0; back--) {
      const previous = lines[back].trim();
      if (previous.startsWith("@")) {
        if (/^@Generated\b/.test(previous)) generated = true;
        continue;
      }
      if (
        !previous ||
        previous.startsWith("*") ||
        previous.startsWith("/*") ||
        previous.startsWith("//")
      )
        continue;
      break;
    }
    if (!generated) members.push({ name: match[1], line: index + 1 });
  }
  return members;
}

export function codeNavigation(
  language: string,
  path: string,
  text: string,
  baseline?: string,
  context: NavigationContext = {},
): NavigationCandidate | null {
  const provenance = entryPoint(language, path, context);
  if (!provenance) return null;
  const header = text.slice(0, 6000);
  const whole = { path, startLine: 1, endLine: lineCount(text), provenance };
  const strip = (value: string) =>
    value
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(/^\s*(?:\/\/|#).*$/gm, "")
      .trim();
  const code = strip(text);

  if (language === "java" && provenance === "Java handwritten source") {
    // A generated header does not make every member generated; @Generated decides.
    if (/@Generated\b/.test(text)) {
      const members = javaHandwrittenMembers(text);
      if (!members.length) return null;
      const names = [...new Set(members.map((member) => member.name))];
      return {
        path,
        startLine: members[0].line,
        endLine: members.at(-1)!.line,
        provenance: `Java members without @Generated: ${names.slice(0, 6).join(", ")}${names.length > 6 ? `, +${names.length - 6} more` : ""}`,
      };
    }
    if (GENERATED_HEADER.test(header)) return null;
    return /\b(?:class|interface|enum|record)\s+\w+/.test(code) ? whole : null;
  }

  if (GENERATED_HEADER.test(header) || (language !== "java" && /@Generated\b/.test(header)))
    return null;

  const comparable = (value: string) =>
    strip(value)
      .replace(/\bextends\s*\|/g, "extends ")
      .replace(/([:=<(,])\s*\|/g, "$1")
      .replace(/azsdk-js-[\w-]+\/[\d.]+(?:-[\w.]+)?/g, "azsdk-js-PACKAGE/VERSION")
      .replace(/\s/g, "");
  if (baseline !== undefined && comparable(text) === comparable(baseline)) return null;

  let substantive: boolean;
  if (language === "python") {
    const pythonCode = code.replace(/"""[\s\S]*?"""|'''[\s\S]*?'''/g, "");
    const hasBody =
      /^[ \t]*(?:async\s+)?def\s+\w+\([\s\S]*?\)(?:[ \t]*->[^\n:]+)?[ \t]*:[ \t]*\n(?:[ \t]*\n)*[ \t]+(?!pass\b|return[ \t]*(?:None)?[ \t]*$)\S/m.test(
        pythonCode,
      );
    // A _patch.py exporting names in __all__ customizes the package even if it only re-binds.
    const exports = /__all__\s*(?::[^=\n]*)?=\s*\[([^\]]*)\]/.exec(pythonCode);
    const exportsNames = Boolean(exports && /["']\w+["']/.test(exports[1]));
    const defines = /^(?:class|(?:async\s+)?def)\s+\w+/m.test(pythonCode);
    substantive =
      provenance === "Python patch"
        ? hasBody || exportsNames
        : hasBody || (defines && /\S/.test(pythonCode));
  } else if (language === "java") {
    substantive =
      /\.\s*(?:replaceBody|setBody|addMethod|addClass|addAnnotation|removeAnnotation|rename|removeMethod|setReturnType|setModifiers|insertBefore|insertAfter|customize|getJavadoc|setJavadoc|addImplementedType|remove)\s*\(/.test(
        code,
      );
  } else if (language === "dotnet")
    substantive = /\b(?:class|struct|enum|interface|record)\s+\w+/.test(code);
  // Go functions, methods (with a receiver) and types.
  else if (language === "go") substantive = /\bfunc\s*(?:\([^)]*\)\s*)?\w+|\btype\s+\w+/.test(code);
  else substantive = /\b(?:function|class|const|interface|type)\s+\w+/.test(code);
  return substantive ? whole : null;
}
